#!/usr/bin/env python3
"""MIND Mono 16: the 8x16 text font, a subset of Terminus Font (SIL OFL 1.1), see fonts/README.md.

Usage: font_gen.py --subset ter-u16n.bdf   write fonts/mind-mono-16.bdf from the Terminus 4.49.1 BDF (patched with
                                           alt/dv1.diff and alt/ij1.diff: Russian forms of в, д, и, й)
       font_gen.py                         write common/font16.rs from fonts/mind-mono-16.bdf
       font_gen.py --check                 fail if common/font16.rs is missing or out of date
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUBSET = ROOT / "fonts" / "mind-mono-16.bdf"
OUT = ROOT / "common" / "font16.rs"
WIDTH, HEIGHT, ASCENT = 8, 16, 12

# Code points kept from the source font: text (English, Russian), panels, bars and graphs.
RANGES = [
    (0x0020, 0x007E),  # ASCII
    (0x00A0, 0x00FF),  # Latin-1
    (0x0400, 0x045F),  # Cyrillic
    (0x0490, 0x0491),  # Ґ ґ
    (0x2010, 0x203F),  # dashes, quotes, bullet, ellipsis, per mille, ‹ ›, ‼
    (0x20AC, 0x20AC),  # €
    (0x2116, 0x2116),  # №
    (0x2122, 0x2122),  # ™
    (0x2190, 0x21FF),  # arrows
    (0x2212, 0x2212),  # −
    (0x2219, 0x221E),  # ∙ √ ∞
    (0x2248, 0x2248),  # ≈
    (0x2260, 0x2265),  # ≠ ≡ ≤ ≥
    (0x2500, 0x259F),  # box drawing, block elements
    (0x25A0, 0x25FF),  # geometric shapes
    (0x2713, 0x2718),  # ✓ ✔ ✗ ✘
    (0x2800, 0x28FF),  # braille patterns: 2x4 dots per cell for graphs
    (0xFFFD, 0xFFFD),  # replacement character
]


def parse_bdf(text):
    """Returns (header lines, {code: (name, [16 row bytes])})."""
    header, glyphs = [], {}
    lines = iter(text.splitlines())
    for line in lines:
        if line.startswith("CHARS "):
            break
        header.append(line)
    for line in lines:
        if not line.startswith("STARTCHAR"):
            continue
        name, code, bbx, rows = line.split(None, 1)[1], None, None, []
        for line in lines:
            if line.startswith("ENCODING"):
                code = int(line.split()[1])
            elif line.startswith("BBX"):
                bbx = tuple(int(v) for v in line.split()[1:])
            elif line == "BITMAP":
                for line in lines:
                    if line == "ENDCHAR":
                        break
                    rows.append(int(line, 16))
                break
        w, h, xoff, yoff = bbx
        cell = [0] * HEIGHT
        top = ASCENT - (yoff + h)
        bytes_per_row = (w + 7) // 8
        for i, row in enumerate(rows):
            y = top + i
            if 0 <= y < HEIGHT:
                # Left-align the row in 8 bits, then apply the x offset.
                value = row >> (bytes_per_row * 8 - 8) if bytes_per_row > 1 else row
                cell[y] = (value >> xoff) & 0xFF
        glyphs[code] = (name, cell)
    return header, glyphs


def wanted(code):
    return any(a <= code <= b for a, b in RANGES)


def write_subset(source):
    header, glyphs = parse_bdf(Path(source).read_text(encoding="latin-1"))
    keep = {c: g for c, g in sorted(glyphs.items()) if wanted(c)}
    rename = {
        "FONT": "FONT -mind-MIND Mono-Medium-R-Normal--16-160-72-72-C-80-ISO10646-1",
        "FAMILY_NAME": 'FAMILY_NAME "MIND Mono"',
        "FOUNDRY": 'FOUNDRY "mind"',
        "NOTICE": 'NOTICE "Licensed under the SIL Open Font License, Version 1.1. Subset of Terminus Font 4.49.1, see fonts/README.md"',
    }
    out = []
    for line in header:
        key = line.split(" ", 1)[0]
        out.append(rename.get(key, line))
    out.append(f"CHARS {len(keep)}")
    for code, (name, cell) in keep.items():
        out += [f"STARTCHAR {name}", f"ENCODING {code}", "SWIDTH 500 0", "DWIDTH 8 0", "BBX 8 16 0 -4", "BITMAP"]
        out += [f"{row:02X}" for row in cell]
        out.append("ENDCHAR")
    out.append("ENDFONT")
    SUBSET.write_text("\n".join(out) + "\n")
    print(f"wrote {SUBSET.relative_to(ROOT)}: {len(keep)} glyphs")


def generate():
    _, glyphs = parse_bdf(SUBSET.read_text(encoding="utf-8"))
    codes = sorted(glyphs)
    assert all(c in glyphs for c in range(0x20, 0x7F)), "ASCII must be complete: glyph() indexes it directly"
    assert codes[:95] == list(range(0x20, 0x7F)) and 0xFFFD in glyphs and codes[-1] <= 0xFFFF
    out = [
        "// Generated by scripts/font_gen.py from fonts/mind-mono-16.bdf; do not edit.",
        "//! MIND Mono 16: 8x16 bitmap font, a subset of Terminus Font 4.49.1",
        "//! (Copyright (C) 2020 Dimitar Toshkov Zhekov, SIL Open Font License 1.1, see fonts/OFL.txt and fonts/README.md).",
        "//! Row 0 is the top; bit 7 of a row byte is the leftmost pixel.",
        "",
        f"pub const WIDTH: usize = {WIDTH};",
        f"pub const HEIGHT: usize = {HEIGHT};",
        f"pub const COUNT: usize = {len(codes)};",
        f"const REPLACEMENT: usize = {codes.index(0xFFFD)};",
        "",
        "/// Code points with a glyph, sorted; `GLYPHS[i]` belongs to `CODES[i]`.",
        f"pub static CODES: [u16; COUNT] = [",
    ]
    for i in range(0, len(codes), 16):
        out.append("    " + ", ".join(f"0x{c:04X}" for c in codes[i:i + 16]) + ",")
    out += ["];", "", "pub static GLYPHS: [[u8; HEIGHT]; COUNT] = ["]
    for c in codes:
        rows = ", ".join(f"0x{r:02X}" for r in glyphs[c][1])
        label = chr(c) if c > 0x20 and c != 0x7F else ""
        out.append(f"    [{rows}], // U+{c:04X} {label}".rstrip())
    out += [
        "];",
        "",
        "/// Bitmap of `ch`; characters without a glyph get U+FFFD.",
        "pub fn glyph(ch: char) -> &'static [u8; HEIGHT] {",
        "    let code = ch as u32;",
        "    if (0x20..0x7F).contains(&code) { return &GLYPHS[(code - 0x20) as usize]; }",
        "    if code <= 0xFFFF { if let Ok(index) = CODES.binary_search(&(code as u16)) { return &GLYPHS[index]; } }",
        "    &GLYPHS[REPLACEMENT]",
        "}",
        "",
        "/// Whether the font has a glyph of its own for `ch`.",
        "pub fn has(ch: char) -> bool { (ch as u32) <= 0xFFFF && CODES.binary_search(&(ch as u32 as u16)).is_ok() }",
        "",
    ]
    return "\n".join(out)


def main():
    args = sys.argv[1:]
    if args[:1] == ["--subset"] and len(args) == 2:
        write_subset(args[1])
        return 0
    text = generate()
    if args == ["--check"]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 scripts/font_gen.py", file=sys.stderr)
            return 1
        return 0
    if args:
        print(__doc__, file=sys.stderr)
        return 2
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
