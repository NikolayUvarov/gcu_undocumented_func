#!/usr/bin/env python3
"""Extract the exact RTL8852B RFE-1/cut-1 tables from a pinned, local BSD source."""
import argparse
import hashlib
from pathlib import Path
import re

COMMIT = "05f7e89ab9731565d8a62e3b5d1ec206485eeb0b"
SOURCE_SHA256 = "8b9b5fc32628037d8dec86cff976913164723d87abe38fd09d229c57b509b42f"
TARGET = 0x10001
TABLES = (("BB", "bb_regs", 1013), ("GAIN", "bb_reg_gain", 66),
          ("RADIO_A", "radioa_regs", 947), ("RADIO_B", "radiob_regs", 932),
          ("NCTL", "nctl_regs", 1320))
PAIR = re.compile(r"\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}\s*,")


def select(rows):
    """Select an exact headline only; never use upstream's unknown-board fallback."""
    headlines = []
    while rows and rows[0][0] >> 28 == 15:
        headlines.append(rows[0][0] & 0x0fffffff)
        rows = rows[1:]
    if not headlines:
        if any(at >> 28 for at, _ in rows):
            raise ValueError("flow control without headlines")
        return rows
    if headlines.count(TARGET) != 1:
        raise ValueError("missing or duplicate exact RFE-1/cut-1 headline")
    selected, active, found, block, pending = [], True, False, False, None
    for at, value in rows:
        kind, target = at >> 28, at & 0x0fffffff
        if kind == 8:
            if block or pending is not None:
                raise ValueError("nested or unfinished branch")
            block, active, found, pending = True, False, False, target
        elif kind == 9:
            if not block or pending is not None:
                raise ValueError("orphan elif")
            active, pending = False, target
        elif kind == 4:
            if not block or pending is None:
                raise ValueError("orphan condition")
            active = not found and pending == TARGET
            found |= active
            pending = None
        elif kind == 10:
            if not block or pending is not None or not found:
                raise ValueError("unmatched fallback is unsupported")
            active = False
        elif kind == 11:
            if not block or pending is not None or not found:
                raise ValueError("unfinished or unmatched branch")
            block, active, found = False, True, False
        elif kind:
            raise ValueError(f"unsupported opcode {at:#x}")
        elif pending is not None:
            raise ValueError("branch data before condition")
        elif active:
            selected.append((at, value))
    if block or pending is not None:
        raise ValueError("unterminated branch")
    return selected


def extract(data):
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise ValueError("source SHA-256 does not match the pinned rtw8852b_table.c")
    source = data.decode("ascii")
    tables = []
    for name, suffix, count in TABLES:
        match = re.search(r"static const struct rtw89_reg2_def rtw89_8852b_phy_" + suffix +
                          r"\[\] = \{(.*?)\n\};", source, re.S)
        if match is None or PAIR.sub("", match[1]).strip():
            raise ValueError(f"unrecognized {suffix} source syntax")
        rows = select([(int(a, 16), int(v, 16)) for a, v in PAIR.findall(match[1])])
        if len(rows) != count:
            raise ValueError(f"unexpected {name} row count: {len(rows)}")
        for at, value in rows:
            if 0xf9 <= at <= 0xfe or value == 0xbabecafe:
                raise ValueError("new delay/bypass requires explicit review")
            if name in ("BB", "NCTL") and (at & 3 or at >= 0x10000):
                raise ValueError("invalid baseband offset")
            if name == "GAIN" and ((at >> 16) & 255 >= 4 or (at >> 8) & 255 >= 2
                                   or (at >> 24, at & 255) not in ((0, 0), (0, 1), (0, 2),
                                       (1, 0), (1, 0x10), (1, 0x11), (1, 0x20), (1, 0x21), (1, 0x29))):
                raise ValueError("unknown gain field requires explicit review")
            if name.startswith("RADIO") and (at & ~0x100ff or value > 0xfffff):
                raise ValueError("invalid RF address or data")
        if name.startswith("RADIO") and sum(at >= 0x10000 for at, _ in rows) != 294:
            raise ValueError("unexpected firmware mirror size")
        tables.append((name, rows))
    return tables


def render(tables):
    lines = ["// SPDX-License-Identifier: BSD-3-Clause",
             "// Copyright(c) 2019-2020 Realtek Corporation; see LICENSES/BSD-3-Clause-rtw89.txt.",
             "// Generated by scripts/hardware/rtw89_phy_tables.py; do not edit.",
             f"// Linux {COMMIT}, rtw8852b_table.c SHA-256 {SOURCE_SHA256}.",
             "//! Exact RFE-1/cut-1 tables; gain entries are software calibration data, never MMIO offsets.", ""]
    for name, rows in tables:
        lines.append(f"pub const {name}: &[(u32, u32)] = &[")
        lines.extend(f"    (0x{at:08x}, 0x{value:08x})," for at, value in rows)
        lines.extend(["];", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="locally obtained pinned rtw8852b_table.c")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] / "rtw89_wifi/src/phy_tables.rs")
    parser.add_argument("--check", action="store_true", help="compare only; never modify the generated file")
    args = parser.parse_args()
    result = render(extract(args.source.read_bytes()))
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit("generated RTL8852B tables differ")
        print("pinned RTL8852B tables match")
    else:
        args.output.write_text(result)
        print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
