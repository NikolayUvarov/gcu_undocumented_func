#!/usr/bin/env python3
"""Reproduce pinned RTL8852B initial 2 GHz TSSI data; no network or device access."""
import argparse
import hashlib
from pathlib import Path
import re
from rtw89_dack_tables import number, parse_body

PINS = {
    'rtw8852b_rfk_table.c': 'ebc6840d2e15c7a9f12fb7d7121ca19bb8acff93524d3902a7ce892e0714fc21',
    'rtw8852b_common.c': '34dcc96967f408ba2b7589af26f49e8ba26c0a822934811e599a2974b86a3afb',
    'rtw8852b_table.c': '8b9b5fc32628037d8dec86cff976913164723d87abe38fd09d229c57b509b42f',
}
TABLES = [('sys_defs',17), ('sys_a_defs_2g',4), ('sys_b_defs_2g',4),
          ('init_txpwr_defs_a',39), ('init_txpwr_defs_b',39),
          ('init_txpwr_he_tb_defs_a',2), ('init_txpwr_he_tb_defs_b',2),
          ('dck_defs_a',3), ('dck_defs_b',3),
          ('dac_gain_defs_a',52), ('dac_gain_defs_b',51),
          ('slope_a_defs_2g',12), ('slope_b_defs_2g',12),
          ('align_a_2g_all_defs',9), ('align_b_2g_all_defs',9),
          ('slope_defs_a',3), ('slope_defs_b',3)]

def one(source, pattern):
    matches = re.findall(pattern, source, re.S)
    if len(matches) != 1:
        raise ValueError('missing or duplicate initializer')
    return matches[0]

def triples(body):
    rows = []
    while body.strip():
        match = re.match(r'\s*\{([^{}]+)\},\s*', body)
        if not match:
            raise ValueError('unrecognized PMAC record')
        args = [number(v) for v in match[1].split(',')]
        if len(args) != 3:
            raise ValueError('wrong PMAC arity')
        # Share the exact field/address checks with the RFK initializer parser.
        parsed = parse_body('RTW89_DECL_RFK_WM('+','.join(str(v) for v in args)+'),')
        rows.append(parsed[0][1])
        body = body[match.end():]
    return rows

def signed_bytes(body):
    if not re.fullmatch(r'\s*-?[0-9]+(?:\s*,\s*-?[0-9]+)*\s*,?\s*', body):
        raise ValueError('unrecognized thermal byte')
    values = [int(v.strip()) for v in body.rstrip().rstrip(',').split(',')]
    if len(values) != 30 or any(not -128 <= v <= 127 for v in values):
        raise ValueError('invalid thermal array')
    return values

def extract(raw):
    sources = {}
    for name, pin in PINS.items():
        if hashlib.sha256(raw[name]).hexdigest() != pin:
            raise ValueError('source SHA-256 mismatch: '+name)
        sources[name] = raw[name].decode('ascii')
    tables = []
    for name, count in TABLES:
        body = one(sources['rtw8852b_rfk_table.c'],
                   r'static const struct rtw89_reg5_def rtw8852b_tssi_'+name+r'\[\] = \{(.*?)\n\};')
        parsed = parse_body(body)
        if len(parsed) != count or any(kind != 'WM' for kind, _ in parsed):
            raise ValueError('unreviewed RFK effects/count: '+name)
        tables.append((name.upper(), [args for _, args in parsed]))
    pmac = triples(one(sources['rtw8852b_common.c'],
                       r'static const struct rtw89_reg3_def rtw8852bx_pmac_ht20_mcs7_tbl\[\] = \{(.*?)\n\};'))
    if len(pmac) != 120:
        raise ValueError('unexpected PMAC count')
    tables.append(('PMAC_HT20_MCS7', pmac))
    thermal = []
    for path in ('a', 'b'):
        for direction in ('n', 'p'):
            name = '2g'+path+'_'+direction
            values = signed_bytes(one(sources['rtw8852b_table.c'],
                r'static const s8 _txpwr_track_delta_swingidx_'+name+r'\[\] = \{(.*?)\};'))
            thermal.append(('THERMAL_'+path.upper()+'_'+direction.upper(), values))
    return tables, thermal

def render(data):
    tables, thermal = data
    lines = ['// SPDX-License-Identifier: BSD-3-Clause',
             '// Copyright(c) 2019-2024 Realtek Corporation; see LICENSES/BSD-3-Clause-rtw89.txt.',
             '// Generated by scripts/hardware/rtw89_tssi_tables.py from the three pinned source files.',
             'pub(crate) type Write = (usize,u32,u32);', '']
    for name, rows in tables:
        lines.append('pub(crate) const '+name+': &[Write] = &[')
        lines.extend('    ('+', '.join(f'0x{v:08x}' for v in row)+'),' for row in rows)
        lines.extend(['];', ''])
    for name, values in thermal:
        lines.append('pub(crate) const '+name+': [i8;30] = ['+', '.join(map(str, values))+'];')
    return '\n'.join(lines)+'\n'

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('source', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = render(extract({name:(args.source/name).read_bytes() for name in PINS}))
    target = Path(__file__).resolve().parents[2]/'rtw89_wifi/src/tssi_tables.rs'
    if args.check:
        if target.read_text() != result:
            raise SystemExit('TSSI table regeneration mismatch')
        print('pinned RTL8852B TSSI tables match')
    else:
        target.write_text(result)

if __name__ == '__main__':
    main()
