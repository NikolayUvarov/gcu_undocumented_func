#!/usr/bin/env python3
"""Generate rtw88_wifi/src/tables.rs from Linux's rtw8821c_table.c (550-DRV-0042).

The tables keep their condition words (the 0x8/0x9/0xA/0xB headlines rtw88's phy.c evaluates): the driver evaluates them
at run time against the chip's cut and the board's RFE type, which only the machine knows. Every entry is kept, in order.

usage: rtw88_tables.py <pinned rtw8821c_table.c> [--check]   (--check: compare with the committed file instead of writing)
"""

import hashlib
import re
import sys
from pathlib import Path

LINUX = "adc218676eef25575469234709c2d87185ca223a"  # v6.12
SOURCE_SHA256 = "ebc2547ddd66b7df434e0ef91319eddf5565c452863c4a0fd64660839d3e9a0c"
OUT = Path(__file__).resolve().parents[2] / "rtw88_wifi/src/tables.rs"

WORDS = ("rtw8821c_mac", "rtw8821c_agc", "rtw8821c_agc_btg_type2", "rtw8821c_bb", "rtw8821c_rf_a")
PG = "rtw8821c_bb_pg_type0"
LMT = "rtw8821c_txpwr_lmt_type0"
# The sizes the pinned source has: a changed source is refused rather than read differently.
SIZES = {"rtw8821c_mac": 138, "rtw8821c_agc": 1200, "rtw8821c_agc_btg_type2": 390, "rtw8821c_bb": 1680,
         "rtw8821c_rf_a": 2712, PG: 15, LMT: 1488}


def body(text, name):
    match = re.search(r"static const [^\n]*\b" + re.escape(name) + r"\[\] = \{(.*?)\n\};", text, re.S)
    if not match:
        raise ValueError(f"{name}: not found")
    return match.group(1)


def numbers(chunk):
    return [int(word, 0) for word in re.findall(r"-?0x[0-9A-Fa-f]+|-?\d+", re.sub(r"/\*.*?\*/", "", chunk, flags=re.S))]


def generate(source):
    text = source.decode()
    out = [
        "// SPDX-License-Identifier: BSD-3-Clause",
        "// Copyright(c) 2018-2019 Realtek Corporation; see LICENSES/BSD-3-Clause-rtw88.txt.",
        "// Generated by scripts/hardware/rtw88_tables.py; do not edit.",
        f"// Linux {LINUX} (v6.12), drivers/net/wireless/realtek/rtw88/rtw8821c_table.c SHA-256 {SOURCE_SHA256}.",
        "//! The RTL8821C's MAC, BB, AGC and RF tables with their condition words, as pairs of (address, value); a power-by-rate",
        "//! table and a power-limit table.",
        "",
        "/// One entry of a power-by-rate table: band, RF path, TX count, register, mask, value.",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct PowerByRate { pub band: u8, pub path: u8, pub tx_num: u8, pub addr: u32, pub mask: u32, pub data: u32 }",
        "",
        "/// One entry of a power-limit table: regulatory domain, band, bandwidth, rate section, channel, limit (0.5 dB units).",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct PowerLimit { pub regd: u8, pub band: u8, pub bw: u8, pub rs: u8, pub ch: u8, pub limit: i8 }",
        "",
    ]
    for name in WORDS:
        values = numbers(body(text, name))
        if len(values) % 2 or len(values) // 2 != SIZES[name]:
            raise ValueError(f"{name}: {len(values)} words, expected {2 * SIZES[name]}")
        rust = name.removeprefix("rtw8821c_").upper()
        out.append(f"pub const {rust}: [(u32, u32); {len(values) // 2}] = [")
        out += [f"    (0x{values[i]:08x}, 0x{values[i + 1]:08x})," for i in range(0, len(values), 2)]
        out += ["];", ""]
    groups = [numbers(g) for g in re.findall(r"\{([^{}]*)\}", body(text, PG))]
    if len(groups) != SIZES[PG] or any(len(g) != 6 for g in groups):
        raise ValueError(f"{PG}: unexpected entries")
    out.append(f"pub const BB_PG_TYPE0: [PowerByRate; {len(groups)}] = [")
    out += [f"    PowerByRate {{ band: {b}, path: {p}, tx_num: {t}, addr: 0x{a:08x}, mask: 0x{m:08x}, data: 0x{d:08x} }},"
            for b, p, t, a, m, d in groups]
    out += ["];", ""]
    groups = [numbers(g) for g in re.findall(r"\{([^{}]*)\}", body(text, LMT))]
    if len(groups) != SIZES[LMT] or any(len(g) != 6 or not -128 <= g[5] <= 127 for g in groups):
        raise ValueError(f"{LMT}: unexpected entries")
    out.append(f"pub const TXPWR_LMT_TYPE0: [PowerLimit; {len(groups)}] = [")
    out += [f"    PowerLimit {{ regd: {r}, band: {b}, bw: {w}, rs: {s}, ch: {c}, limit: {l} }}," for r, b, w, s, c, l in groups]
    out += ["];", ""]
    return "\n".join(out)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    source = Path(sys.argv[1]).read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    if digest != SOURCE_SHA256:
        sys.exit(f"rtw88_tables: {sys.argv[1]} has SHA-256 {digest}, not the pinned {SOURCE_SHA256}")
    rust = generate(source)
    if "--check" in sys.argv[2:]:
        if OUT.read_text() != rust:
            sys.exit(f"rtw88_tables: {OUT} differs from the pinned source's tables")
        print(f"rtw88_tables: {OUT} matches")
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(rust)
        print(f"rtw88_tables: {OUT} written")


if __name__ == "__main__":
    main()
