#!/usr/bin/env python3
"""Build complete graph/package fixtures and independent explicit PyTorch oracles."""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import sys
import zipfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference-root', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    archive = root / 'reference/qwen-spline-lab-v0.1.0.zip'
    if hashlib.sha256(archive.read_bytes()).hexdigest() != '5e27aab03013e16ac447f12e7093b39ca36167fb20b9b74368661ea425a38b25':
        parser.error('Reference archive SHA-256 mismatch')
    with zipfile.ZipFile(archive) as bundle:
        for name in ('__init__.py', 'representations.py'):
            relative = 'src/qwen_spline_lab/' + name
            if (args.reference_root / relative).read_bytes() != bundle.read('qwen-spline-lab/' + relative):
                parser.error('Reference source mismatch: ' + relative)
    sys.path.insert(0, str(args.reference_root / 'src'))
    import torch
    from qwen_spline_lab.representations import BlockSpec, build_block
    torch.set_num_threads(1)
    torch.manual_seed(42)
    numerical_bytes = (root / 'tests/fixtures/f64-v5.json').read_bytes()
    numerical = json.loads(numerical_bytes)
    execution = {'schema': 'nrl.execution/0', 'backend': 'cpu-scalar', 'dtype': 'f64', 'layout': 'row-major',
                 'max_batch_rows': 256, 'max_activation_values': 65536}

    def source(name):
        return {'identifier': 'synthetic://nrl-' + name, 'sha256': None,
                'licence': 'MIT; deterministic synthetic fixture, no pretrained weights',
                'notices': ['Generated by NRL fixture tools.', 'No model quality or optimization claim.']}

    def descriptor(graph, ties=None):
        return {'family': 'feed-forward', 'adapter': 'nrl.feed-forward', 'adapter_version': 0,
                'configuration': graph, 'preprocessor': 'identity-f64/0', 'tasks': ['regression-vector/0'],
                'state': 'stateless', 'tied_objects': ties or []}

    def affine(inputs, outputs, weights, bias):
        return {'kind': 'affine', 'data': {'schema': 'nrl.affine/0', 'shape': [inputs, outputs], 'weights': weights, 'bias': bias}}

    def node(name, operator, **fields):
        return {'id': name, 'op': {'operator': operator, **fields}}

    def linear(data):
        data = data['data']
        layer = torch.nn.Linear(data['shape'][0], data['shape'][1], bias=bool(data['bias'])).double()
        with torch.no_grad():
            layer.weight.copy_(torch.tensor(data['weights'], dtype=torch.float64).reshape(layer.weight.shape))
            if data['bias']:
                layer.bias.copy_(torch.tensor(data['bias'], dtype=torch.float64))
        return layer

    def gated(data):
        kind = data['representation']
        n, w, _ = data['shape']
        block = build_block(BlockSpec(kind, n, max(w, data['selection']['original_channels'] if data['selection'] else w),
                                     width=w, rank=data['factors']['rank'] if data['factors'] else 0,
                                     knots=data['spline']['knots'] if data['spline'] else 4)).double()
        with torch.no_grad():
            for name, layer in (('gate', block.gate_proj), ('up', block.up_proj), ('down', block.down_proj)):
                projection = layer.left if kind == 'svd' else layer
                if kind == 'svd':
                    for side in ('left', 'right'):
                        matrix = getattr(layer, side).weight
                        matrix.copy_(torch.tensor(data['factors'][name + '_' + side], dtype=torch.float64).reshape(matrix.shape))
                else:
                    layer.weight.copy_(torch.tensor(data[name], dtype=torch.float64).reshape(layer.weight.shape))
                if data['bias'] and data['bias'][name]:
                    projection.bias = torch.nn.Parameter(torch.tensor(data['bias'][name], dtype=torch.float64))
            if data['spline']:
                for field in ('low', 'high', 'values'):
                    target = getattr(block.activation, field)
                    target.copy_(torch.tensor(data['spline'][field], dtype=torch.float64).reshape(target.shape))
        return block

    objects = {f'block{i}': {'kind': 'gated', 'data': copy.deepcopy(numerical['cases'][i+5]['artifact'])} for i in range(5)}
    objects['embed'] = affine(3, 3, [.3, -.2, .1, -.1, .4, .2, .2, .1, -.3], [.1, -.2, .05])
    objects['head'] = affine(3, 2, [.3, -.4, .2, -.1, .5, .6], [.1, -.2])
    nodes = [node('left', 'affine', input='input', object='embed'), node('right', 'affine', input='input', object='embed'),
             node('left_silu', 'silu', input='left'), node('right_relu', 'relu', input='right'),
             node('features', 'add', left='left_silu', right='right_relu')]
    nodes += [node(f'g{i}', 'gated', input='features', object=f'block{i}') for i in range(5)]
    last = 'g0'
    for i in range(1, 5):
        nodes.append(node(f'sum{i}', 'add', left=last, right=f'g{i}'))
        last = f'sum{i}'
    nodes.append(node('prediction', 'affine', input=last, object='head'))
    graph = {'schema': 'nrl.graph/0', 'input_width': 3, 'nodes': nodes, 'output': 'prediction'}
    definition = {'schema': 'nrl.model-definition/0', 'descriptor': descriptor(graph, [{'object': 'embed', 'nodes': ['left', 'right']}]),
                  'execution': execution, 'sources': [source('composed-graph-v0')], 'objects': objects}
    replacement_objects = {'block0': {'kind': 'gated', 'data': copy.deepcopy(numerical['cases'][6]['artifact'])},
                           'head': copy.deepcopy(objects['head'])}
    replacement_objects['head']['data']['bias'] = [.15, -.25]
    replacements = {'schema': 'nrl.replacements/0', 'source': source('manual-fixture-replacements-v0'),
                    'reason': 'Synthetic manual parameter replacement; no quality or speed claim.', 'objects': replacement_objects}
    x = torch.tensor([[.2, -.7, 1.1], [4.2, -3.1, 2.3], [-2.5, .4, -1.2]], dtype=torch.float64)

    def explicit_forward(parameters):
        embed = linear(parameters['embed'])
        features = torch.nn.functional.silu(embed(x)) + torch.relu(embed(x))
        block_outputs = [gated(parameters[f'block{i}']['data'])(features) for i in range(5)]
        total = block_outputs[0]
        for value in block_outputs[1:]:
            total = total + value
        return linear(parameters['head'])(total)

    modules = torch.nn.ModuleDict({key: gated(value['data']) if value['kind'] == 'gated' else linear(value) for key, value in objects.items()})
    parameter_values = sum(p.numel() for p in modules.parameters())
    numeric_values = parameter_values + sum(b.numel() for b in modules.buffers())
    original = explicit_forward(objects).detach().flatten().tolist()
    changed = copy.deepcopy(objects)
    changed.update(replacement_objects)
    replaced = explicit_forward(changed).detach().flatten().tolist()
    plain_objects = {'hidden': affine(2, 4, [.2, -.3, .4, .1, -.2, .5, .3, -.1], [.1, -.1, .2, .05]),
                     'readout': affine(4, 1, [.4, -.2, .3, .1], [-.05])}
    plain_graph = {'schema': 'nrl.graph/0', 'input_width': 2,
                   'nodes': [node('hidden', 'affine', input='input', object='hidden'), node('relu', 'relu', input='hidden'),
                             node('prediction', 'affine', input='relu', object='readout')], 'output': 'prediction'}
    plain_definition = {'schema': 'nrl.model-definition/0', 'descriptor': descriptor(plain_graph), 'execution': execution,
                        'sources': [source('plain-feed-forward-v0')], 'objects': plain_objects}
    plain_x = torch.tensor([[.2, -.7], [1.1, .3], [-.4, .8]], dtype=torch.float64)
    plain_y = linear(plain_objects['readout'])(torch.relu(linear(plain_objects['hidden'])(plain_x)))
    a = affine(2, 3, [.2, -.3, .4, .1, -.2, .5], [.1, -.1, .2])
    layer = linear(a)
    ax = torch.tensor([[.3, -.7], [1.2, .4]], dtype=torch.float64, requires_grad=True)
    dy = torch.tensor([[.2, -.4, .3], [-.1, .5, .2]], dtype=torch.float64)
    ay = layer(ax)
    (ay * dy).sum().backward()
    oracle = {'schema': 'nrl.model-oracle/0', 'object_count': len(objects), 'numeric_values': numeric_values, 'trainable_values': parameter_values, 'torch': torch.__version__, 'numerical_fixture_sha256': hashlib.sha256(numerical_bytes).hexdigest(),
              'input': x.flatten().tolist(), 'original_output': original, 'overlay_output': replaced,
              'plain_input': plain_x.flatten().tolist(), 'plain_output': plain_y.detach().flatten().tolist(),
              'affine': {'data': a['data'], 'input': ax.detach().flatten().tolist(), 'dy': dy.flatten().tolist(),
                         'output': ay.detach().flatten().tolist(), 'dx': ax.grad.flatten().tolist(),
                         'dw': layer.weight.grad.flatten().tolist(), 'db': layer.bias.grad.flatten().tolist()}}
    files = {'definition.json': definition, 'replacements.json': replacements, 'plain.json': plain_definition,
             'input.json': x.flatten().tolist(), 'plain-input.json': plain_x.flatten().tolist(), 'expected.json': oracle}
    if not args.check:
        args.output.mkdir()
    for name, value in files.items():
        payload = (json.dumps(value, sort_keys=True, indent=2, allow_nan=False) + '\n').encode()
        if args.check:
            if (args.output / name).read_bytes() != payload:
                parser.error('Regenerated fixture differs: ' + name)
        else:
            (args.output / name).write_bytes(payload)
    print(json.dumps({'files': len(files), 'check': args.check, 'oracle_sha256': hashlib.sha256((args.output / 'expected.json').read_bytes()).hexdigest()}, sort_keys=True))


if __name__ == '__main__':
    main()
